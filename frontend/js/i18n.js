let lang = 'en';
let vars = { who: 'Don Manuel' };

export function detectLang(saved, navLang) {
  if (saved === 'en' || saved === 'es') return saved;
  return /^es\b/i.test(navLang || '') ? 'es' : 'en';
}

export function setLang(l) {
  lang = DICT[l] ? l : 'en';
}
export const getLang = () => lang;
export function setVars(v) {
  vars = { ...vars, ...v };
}

export function t(key, extra, forLang) {
  const d = DICT[forLang || lang];
  let s = d && d[key] !== undefined ? d[key] : DICT.en[key];
  if (s === undefined) return key;
  const all = { ...vars, ...(extra || {}) };
  return s.replace(/\{(\w+)\}/g, (m, k) => (all[k] !== undefined ? String(all[k]) : m));
}

// Fills every element that declares a key. Works on text, placeholders and aria labels.
export function applyDom(root) {
  const r = root || document;
  r.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  r.querySelectorAll('[data-i18n-ph]').forEach((el) => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph')));
  });
  r.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
  });
  document.documentElement.setAttribute('lang', lang);
}
